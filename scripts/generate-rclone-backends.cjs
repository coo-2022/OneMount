'use strict';
const fs = require('node:fs');
const path = require('node:path');
const modulePath = 'github.com/coo-2022/OneMount/engine-src/rclone';
function generate(root = path.resolve(__dirname, '../engine-src/rclone')) {
  const dir = path.join(root, 'backend');
  const names = [];
  for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    if (entry.name.startsWith('.') || ['all','internal','testdata'].includes(entry.name)) continue;
    if (entry.isSymbolicLink()) throw new Error('Backend directories must not be symlinks: '+entry.name);
    if (!entry.isDirectory()) continue;
    if (!/^[a-z][a-z0-9]*$/.test(entry.name)) throw new Error('Backend name must use lowercase letters and digits: '+entry.name);
    const files = fs.readdirSync(path.join(dir, entry.name));
    if (files.includes('go.mod')) throw new Error('Backends must share the engine Go module: '+entry.name);
    if (!files.some(f=>f.endsWith('.go')&&!f.endsWith('_test.go'))) throw new Error('Backend is missing a Go entry package: '+entry.name);
    names.push(entry.name);
  }
  names.sort();
  const content = '// Code generated by scripts/generate-rclone-backends.cjs; DO NOT EDIT.\npackage all\n' +
    (names.length ? '\nimport (\n'+names.map(n=>'\t_ "'+modulePath+'/backend/'+n+'"').join('\n')+'\n)\n' : '');
  const out = path.join(dir, 'all', 'all.go');
  fs.mkdirSync(path.dirname(out), {recursive:true});
  if (!fs.existsSync(out)||fs.readFileSync(out,'utf8')!==content) fs.writeFileSync(out,content);
  return names;
}
if (require.main===module) console.log('Custom backends:',generate().join(', ')||'(none yet)');
module.exports={generate};
